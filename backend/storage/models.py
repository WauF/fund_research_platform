"""Database tables. Every change here needs a matching Alembic migration in migrations/versions/."""

from datetime import UTC, date, datetime
from decimal import Decimal
from typing import Any
from uuid import UUID

from sqlalchemy import (
    JSON,
    BigInteger,
    Date,
    DateTime,
    Enum,
    ForeignKey,
    Integer,
    Numeric,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    func,
)
from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import Mapped, mapped_column, relationship

from schemas.holding import AssetType, ReportKind, Status, WeightBasis
from storage.db import Base

# SQLite (tests) only auto-increments INTEGER PRIMARY KEY; Postgres gets BIGINT.
BigId = BigInteger().with_variant(Integer(), "sqlite")
# JSONB on Postgres, plain JSON elsewhere (db-migrations skill, rule 10).
JsonColumn = JSON().with_variant(postgresql.JSONB(), "postgresql")
# Money and quantities: wide enough for 66.8 bn TL fund totals, 6 decimals for computed values.
Amount = Numeric(24, 6)
# Weights are fractions (12.02% -> 0.1202); look-through fixtures carry up to ~10 decimals.
Weight = Numeric(16, 10)


def str_enum(enum_cls: type, name: str, length: int = 32) -> Enum:
    """VARCHAR + CHECK instead of a native Postgres ENUM (db-migrations skill, rule 8)."""
    return Enum(
        enum_cls,
        name=name,
        native_enum=False,
        create_constraint=True,
        length=length,
        values_callable=lambda members: [m.value for m in members],
    )


class Document(Base):
    """An uploaded PDF. One row per distinct file content: sha256 is unique."""

    __tablename__ = "documents"

    id: Mapped[int] = mapped_column(primary_key=True)
    sha256: Mapped[str] = mapped_column(String(64), unique=True)
    # Name of the first upload; later uploads of the same content keep this row as is.
    original_filename: Mapped[str] = mapped_column(String(255))
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    storage_key: Mapped[str] = mapped_column(String(255))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())


class ExtractionRun(Base):
    """One extraction attempt on one document (LLM or rule-based baseline).

    The id is generated by the extraction code before the run is saved, because every Holding
    already carries it (schemas.holding: extraction_run_id is a UUID). A document can have many
    runs; which one is served is decided in storage.extractions (decision 0008).
    """

    __tablename__ = "extraction_runs"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True)
    document_id: Mapped[int] = mapped_column(ForeignKey("documents.id"), index=True)
    # "baseline" for the rule-based extractor, otherwise the model name as the provider gives it.
    model: Mapped[str] = mapped_column(String(128))
    prompt_version: Mapped[str | None] = mapped_column(String(64))
    # The model's reply exactly as received, for reproducibility. None for the baseline.
    raw_output: Mapped[str | None] = mapped_column(Text)
    # needs_review if any check failed or any record needs review; ok otherwise.
    status: Mapped[Status] = mapped_column(str_enum(Status, "status", 16))
    # Validation and conversion problems: [{"code", "message", "row_no"}]; row_no None = report.
    issues: Mapped[list[dict[str, Any]]] = mapped_column(JsonColumn, default=list)
    # Set in Python with microseconds: "latest run" must not tie when two runs land in one second.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC), server_default=func.now()
    )

    holdings: Mapped[list["HoldingRow"]] = relationship(
        back_populates="run", cascade="all, delete-orphan", order_by="HoldingRow.row_no"
    )
    summary: Mapped["ReportSummaryRow | None"] = relationship(
        back_populates="run", cascade="all, delete-orphan"
    )


class _ReportScopedColumns:
    """Columns of schemas.holding._ReportScoped, shared by holdings and report_summaries."""

    fund_code: Mapped[str] = mapped_column(String(6), index=True)
    period_start: Mapped[date] = mapped_column(Date)
    period_end: Mapped[date] = mapped_column(Date)
    report_kind: Mapped[ReportKind] = mapped_column(str_enum(ReportKind, "report_kind", 16))
    page: Mapped[int] = mapped_column(Integer)
    quote: Mapped[str] = mapped_column(Text)
    status: Mapped[Status] = mapped_column(str_enum(Status, "status", 16))


class HoldingRow(_ReportScopedColumns, Base):
    """One row of a report's portfolio table: schemas.holding.Holding."""

    __tablename__ = "holdings"

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    extraction_run_id: Mapped[UUID] = mapped_column(
        ForeignKey("extraction_runs.id", ondelete="CASCADE")
    )
    # Not unique per (fund, isin): Garanti reports list the same ISIN once per purchase lot.
    row_no: Mapped[int] = mapped_column(Integer)
    name: Mapped[str] = mapped_column(Text)
    asset_type: Mapped[AssetType] = mapped_column(str_enum(AssetType, "asset_type"))
    isin: Mapped[str | None] = mapped_column(String(12), index=True)
    instrument_code: Mapped[str | None] = mapped_column(String(32))
    held_fund_code: Mapped[str | None] = mapped_column(String(6))
    # Signs are not restricted: short positions are printed negative.
    nominal: Mapped[Decimal | None] = mapped_column(Amount)
    value: Mapped[Decimal] = mapped_column(Amount)
    currency: Mapped[str] = mapped_column(String(3))
    weight: Mapped[Decimal] = mapped_column(Weight)
    weight_basis: Mapped[WeightBasis] = mapped_column(str_enum(WeightBasis, "weight_basis", 16))

    run: Mapped[ExtractionRun] = relationship(back_populates="holdings")

    # Row order is unique within a run; the constraint also indexes extraction_run_id.
    __table_args__ = (UniqueConstraint("extraction_run_id", "row_no"),)


class ReportSummaryRow(_ReportScopedColumns, Base):
    """A report's fund total value table (section IV): schemas.holding.ReportSummary."""

    __tablename__ = "report_summaries"

    id: Mapped[int] = mapped_column(BigId, primary_key=True)
    # One summary per run.
    extraction_run_id: Mapped[UUID] = mapped_column(
        ForeignKey("extraction_runs.id", ondelete="CASCADE"), unique=True
    )
    portfolio_value: Mapped[Decimal] = mapped_column(Amount)
    cash_equivalents: Mapped[Decimal] = mapped_column(Amount)
    receivables: Mapped[Decimal] = mapped_column(Amount)
    other_assets: Mapped[Decimal] = mapped_column(Amount)
    liabilities: Mapped[Decimal] = mapped_column(Amount)  # always zero or negative
    total_value: Mapped[Decimal] = mapped_column(Amount)
    currency: Mapped[str] = mapped_column(String(3))

    run: Mapped[ExtractionRun] = relationship(back_populates="summary")
